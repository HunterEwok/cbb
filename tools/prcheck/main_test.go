const owner = "88090358+HunterEwok@users.noreply.github.com"

func TestCheckCommit(t *testing.T) {
	ok := []commit{
		{"a", "Claude", assistantEmail, "Claude", assistantEmail, "Fix it\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"},
		{"b", "Evgenii Russkikh", owner, "GitHub", "noreply@github.com", "Merge branch 'main'"},
		{"c", "dependabot[bot]", "49699333+dependabot[bot]@users.noreply.github.com", "GitHub", "noreply@github.com", "Bump x"},
	}
	for _, c := range ok {
		if bad := checkCommit(c); len(bad) != 0 {
			t.Errorf("%s: %v", c.hash, bad)
		}
	}
	wrong := []commit{
		{"d", "t", "t@t", "t", "t@t", "Merge #504 into this PR"},
		{"e", "Claude", assistantEmail, "Claude", assistantEmail, "Fix\n\nCo-authored-by: someone <someone@example.com>\n"},
		{"f", "Claude Opus 5.5", assistantEmail, "Claude", assistantEmail, "Fix"},
		{"g", "root", "root@localhost", "Claude", assistantEmail, "Fix"},
	}
	for _, c := range wrong {
		if bad := checkCommit(c); len(bad) == 0 {
			t.Errorf("%s passed", c.hash)
		}
	}
}

