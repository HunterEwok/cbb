// TestCommits reads a real repository's commits, a merge among them.
func TestCommits(t *testing.T) {
	dir := t.TempDir()
	git := func(env []string, args ...string) string {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		cmd.Env = append(cmd.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
		cmd.Env = append(cmd.Env, env...)
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return strings.TrimSpace(string(out))
	}
	as := func(name, email string) []string {
		return []string{"GIT_AUTHOR_NAME=" + name, "GIT_AUTHOR_EMAIL=" + email, "GIT_COMMITTER_NAME=" + name, "GIT_COMMITTER_EMAIL=" + email}
	}
	claude := as("Claude", assistantEmail)
	git(nil, "init", "-q", "-b", "main")
	git(claude, "commit", "-q", "--allow-empty", "-m", "base")
	base := git(nil, "rev-parse", "HEAD")
	git(nil, "checkout", "-q", "-b", "side")
	git(claude, "commit", "-q", "--allow-empty", "-m", "side\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
	git(nil, "checkout", "-q", "main")
	git(claude, "commit", "-q", "--allow-empty", "-m", "first\n\nwith a body")
	git(as("t", "t@t"), "merge", "-q", "--no-ff", "-m", "Merge side", "side")

	t.Chdir(dir)
	list, err := commits(base, "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	if len(list) != 3 {
		t.Fatalf("got %d commits, want 3", len(list))
	}
	var bad []string
	for _, c := range list {
		bad = append(bad, checkCommit(c)...)
	}
	if len(bad) != 2 || !strings.Contains(bad[0], "t@t") {
		t.Fatalf("got %v, want the merge's author and committer", bad)
	}
}
