//! The registry of bounds: every limit of the 0.6 format in one place, with
//! its class, the widest case it is sized for, the refusal a reader gives
//! past it and what reaches it (a test of the core, or a vector as
//! `vec:<file>:<name>`). Each value is the constant the code uses, so the
//! table cannot drift from it; `testdata/format/bounds.json` is this table
//! written out, which gen.py and the Go check compare their own numbers
//! with, and a test fails on a public number of the format modules that is
//! neither here nor exempted with its reason ([`EXEMPT`]).
//!
//! The rule between versions (N works with N−1): a [`Class::Frozen`] bound
//! never changes, a later need takes a new field, message or label. A
//! [`Class::Stated`] limit, what a writer keeps and the person is promised,
//! may be raised in version N only up to what N−1's reader already takes
//! (its frozen bound), so that N−1 still reads what N writes. A
//! [`Class::Reader`] bound is one device's own budget, a time or a count it
//! keeps, never on the wire, and may change in any version.

/// How a bound may change.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Class {
    /// A number of the format: readers depend on it, it never changes.
    Frozen,
    /// A writer's limit the person is promised; raised only up to what the
    /// previous version's reader takes.
    Stated,
    /// One device's budget, never on the wire.
    Reader,
}

impl Class {
    pub fn name(&self) -> &'static str {
        match self {
            Class::Frozen => "frozen",
            Class::Stated => "stated",
            Class::Reader => "reader",
        }
    }
}

/// One bound.
#[derive(Clone, Copy, Debug)]
pub struct Bound {
    /// The constant, by its path under the crate.
    pub name: &'static str,
    pub value: u64,
    pub class: Class,
    /// The widest case it is sized for.
    pub widest: &'static str,
    /// The rule a reader gives past it; empty for a budget nothing reads
    /// back (a writer's split, a local count that drops the oldest).
    pub refusal: &'static str,
    /// What reaches it: test functions of the core, or `vec:<file>:<name>`.
    pub reached: &'static [&'static str],
}

const fn b(
    name: &'static str,
    value: u64,
    class: Class,
    widest: &'static str,
    refusal: &'static str,
    reached: &'static [&'static str],
) -> Bound {
    Bound { name, value, class, widest, refusal, reached }
}

